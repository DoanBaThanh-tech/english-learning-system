/* ===== 1. NGƯỜI DÙNG (CN 1, 6) ===== */
CREATE TABLE Users(
 Id INT IDENTITY PRIMARY KEY, Email NVARCHAR(256) NOT NULL UNIQUE, PasswordHash NVARCHAR(255) NOT NULL,
 DisplayName NVARCHAR(100) NOT NULL, AvatarUrl NVARCHAR(500) NULL,
 CurrentLevelId TINYINT NULL REFERENCES Levels(Id), DailyWordGoal SMALLINT NOT NULL DEFAULT 20 CHECK(DailyWordGoal>0),
 TimeZoneId NVARCHAR(64) NOT NULL DEFAULT 'SE Asia Standard Time',
 CreatedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME(), IsActive BIT NOT NULL DEFAULT 1);
CREATE TABLE RefreshTokens(
 Id BIGINT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
 TokenHash BINARY(32) NOT NULL UNIQUE, ExpiresAt DATETIME2(0) NOT NULL, RevokedAt DATETIME2(0) NULL);
CREATE TABLE UserDailyStats(  -- CN 6, 12: streak và biểu đồ tính từ bảng này
 Id BIGINT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
 StatDate DATE NOT NULL, WordsLearned SMALLINT NOT NULL DEFAULT 0, WordsReviewed SMALLINT NOT NULL DEFAULT 0,
 MinutesStudied SMALLINT NOT NULL DEFAULT 0, GoalMet BIT NOT NULL DEFAULT 0, CONSTRAINT UQ_DailyStats UNIQUE(UserId,StatDate));

GO
/* ===== 2. TỪ ĐIỂN (cache phần đã tra, CN 2, 4, 9) ===== */
CREATE TABLE Words(Id INT IDENTITY PRIMARY KEY, Lemma NVARCHAR(100) NOT NULL UNIQUE, CreatedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME());
CREATE TABLE WordPronunciations(
 Id INT IDENTITY PRIMARY KEY, WordId INT NOT NULL REFERENCES Words(Id) ON DELETE CASCADE,
 Accent CHAR(2) NOT NULL CHECK(Accent IN('US','UK')), Ipa NVARCHAR(100) NOT NULL, AudioUrl NVARCHAR(500) NULL,
 CONSTRAINT UQ_WordAccent UNIQUE(WordId,Accent));
CREATE TABLE WordSenses(
 Id INT IDENTITY PRIMARY KEY, WordId INT NOT NULL REFERENCES Words(Id) ON DELETE CASCADE,
 PartOfSpeechId TINYINT NOT NULL REFERENCES PartsOfSpeech(Id), LevelId TINYINT NULL REFERENCES Levels(Id),
 DefinitionEn NVARCHAR(1000) NOT NULL, SenseOrder SMALLINT NOT NULL DEFAULT 1, Source NVARCHAR(50) NULL,
 CONSTRAINT UQ_SenseOrder UNIQUE(WordId,SenseOrder));
CREATE TABLE SenseTranslations(
 Id INT IDENTITY PRIMARY KEY, SenseId INT NOT NULL REFERENCES WordSenses(Id) ON DELETE CASCADE,
 MeaningVi NVARCHAR(500) NOT NULL, Source NVARCHAR(50) NULL, IsVerified BIT NOT NULL DEFAULT 0,
 CONSTRAINT UQ_SenseTrans UNIQUE(SenseId,MeaningVi));
CREATE TABLE Examples(
 Id INT IDENTITY PRIMARY KEY, SenseId INT NOT NULL REFERENCES WordSenses(Id) ON DELETE CASCADE,
 SentenceEn NVARCHAR(1000) NOT NULL, SentenceVi NVARCHAR(1000) NULL, Source NVARCHAR(50) NULL);
CREATE TABLE TranslationCache(  -- CN 9: dịch theo ngữ cảnh, mỗi (từ, câu) gọi AI 1 lần
 Id BIGINT IDENTITY PRIMARY KEY, WordId INT NOT NULL REFERENCES Words(Id) ON DELETE CASCADE,
 SentenceHash BINARY(32) NOT NULL, SentenceText NVARCHAR(1000) NOT NULL,
 ChosenSenseId INT NULL REFERENCES WordSenses(Id), MeaningVi NVARCHAR(500) NOT NULL,
 ConfidencePct TINYINT NULL CHECK(ConfidencePct BETWEEN 0 AND 100), Model NVARCHAR(50) NULL,
 CreatedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME(), CONSTRAINT UQ_TransCache UNIQUE(WordId,SentenceHash));

GO
/* ===== 3. NGUỒN NỘI DUNG (CN 10, 11, 15) ===== */
CREATE TABLE Sources(  -- văn bản/web/video/tài liệu OPC bạn dán vào
 Id INT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
 SourceType NVARCHAR(20) NOT NULL CHECK(SourceType IN('web','text','video','document')),
 Title NVARCHAR(300) NOT NULL, Url NVARCHAR(1000) NULL, Content NVARCHAR(MAX) NULL, CreatedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME());
CREATE TABLE ReadingPassages(
 Id INT IDENTITY PRIMARY KEY, LevelId TINYINT NOT NULL REFERENCES Levels(Id), SourceId INT NULL REFERENCES Sources(Id),
 Title NVARCHAR(300) NOT NULL, Topic NVARCHAR(100) NULL, Body NVARCHAR(MAX) NOT NULL);
CREATE TABLE UserPassageProgress(
 Id INT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
 PassageId INT NOT NULL REFERENCES ReadingPassages(Id) ON DELETE CASCADE, ProgressPct TINYINT NOT NULL DEFAULT 0 CHECK(ProgressPct<=100),
 LastReadAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME(), CONSTRAINT UQ_UserPassage UNIQUE(UserId,PassageId));
CREATE TABLE GeneratedLessons(
 Id INT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE, SourceId INT NULL REFERENCES Sources(Id),
 LevelId TINYINT NULL REFERENCES Levels(Id), Title NVARCHAR(300) NOT NULL, CreatedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME());
CREATE TABLE LessonItems(
 LessonId INT NOT NULL REFERENCES GeneratedLessons(Id) ON DELETE CASCADE, SenseId INT NOT NULL REFERENCES WordSenses(Id),
 ItemOrder SMALLINT NOT NULL, ContextSentence NVARCHAR(1000) NULL, PRIMARY KEY(LessonId,SenseId));

GO
/* ===== 4. SỔ TỪ CÁ NHÂN + ÔN TẬP (CN 3, 5, 7, 8) ===== */
CREATE TABLE WordFolders(Id INT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE, Name NVARCHAR(100) NOT NULL, CONSTRAINT UQ_Folder UNIQUE(UserId,Name));
CREATE TABLE Tags(Id INT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE, Name NVARCHAR(50) NOT NULL, CONSTRAINT UQ_Tag UNIQUE(UserId,Name));
CREATE TABLE UserWords(  -- 1 dòng = người dùng lưu 1 nghĩa của 1 từ
 Id INT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE, SenseId INT NOT NULL REFERENCES WordSenses(Id),
 FolderId INT NULL REFERENCES WordFolders(Id), SourceId INT NULL REFERENCES Sources(Id),
 ContextSentence NVARCHAR(1000) NULL, Note NVARCHAR(500) NULL,
 Status NVARCHAR(10) NOT NULL DEFAULT 'new' CHECK(Status IN('new','learning','mastered')), AddedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME(),
 CONSTRAINT UQ_UserSense UNIQUE(UserId,SenseId));
CREATE TABLE UserWordTags(UserWordId INT NOT NULL REFERENCES UserWords(Id) ON DELETE CASCADE, TagId INT NOT NULL REFERENCES Tags(Id), PRIMARY KEY(UserWordId,TagId));
CREATE TABLE SrsStates(  -- CN 8 (SM-2), quan hệ 1-1 với UserWords
 UserWordId INT PRIMARY KEY REFERENCES UserWords(Id) ON DELETE CASCADE, EaseFactor DECIMAL(4,2) NOT NULL DEFAULT 2.50 CHECK(EaseFactor>=1.30),
 IntervalDays INT NOT NULL DEFAULT 0, Repetitions INT NOT NULL DEFAULT 0, DueAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME());
CREATE INDEX IX_Srs_Due ON SrsStates(DueAt);
CREATE TABLE StudySessions(
 Id BIGINT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE, Mode NVARCHAR(10) NOT NULL CHECK(Mode IN('learn','review')),
 StartedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME(), EndedAt DATETIME2(0) NULL);
CREATE TABLE StudyAnswers(
 Id BIGINT IDENTITY PRIMARY KEY, SessionId BIGINT NOT NULL REFERENCES StudySessions(Id) ON DELETE CASCADE,
 UserWordId INT NOT NULL REFERENCES UserWords(Id), ExerciseTypeId TINYINT NOT NULL REFERENCES ExerciseTypes(Id),
 UserAnswer NVARCHAR(500) NULL, IsCorrect BIT NOT NULL, ResponseMs INT NULL, AnsweredAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME());
CREATE TABLE ReviewLogs(
 Id BIGINT IDENTITY PRIMARY KEY, UserWordId INT NOT NULL REFERENCES UserWords(Id) ON DELETE CASCADE,
 StudyAnswerId BIGINT NULL REFERENCES StudyAnswers(Id), Quality TINYINT NOT NULL CHECK(Quality BETWEEN 0 AND 5),
 IntervalBefore INT NOT NULL, IntervalAfter INT NOT NULL, ReviewedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME());
CREATE INDEX IX_ReviewLogs ON ReviewLogs(UserWordId,ReviewedAt);

GO
/* ===== 5. PHÁT ÂM + CHATBOT + NHẬT KÝ LỖI (CN 13, 14) ===== */
CREATE TABLE PronunciationAttempts(
 Id BIGINT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE, WordId INT NULL REFERENCES Words(Id),
 ReferenceText NVARCHAR(500) NOT NULL, AudioUrl NVARCHAR(500) NULL, OverallScore TINYINT NOT NULL CHECK(OverallScore<=100),
 CreatedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME());
CREATE TABLE PronunciationPhonemeScores(
 Id BIGINT IDENTITY PRIMARY KEY, AttemptId BIGINT NOT NULL REFERENCES PronunciationAttempts(Id) ON DELETE CASCADE,
 Phoneme NVARCHAR(10) NOT NULL, Score TINYINT NOT NULL CHECK(Score<=100), Feedback NVARCHAR(300) NULL);
CREATE TABLE ChatScenarios(Id INT IDENTITY PRIMARY KEY, LevelId TINYINT NULL REFERENCES Levels(Id), Name NVARCHAR(100) NOT NULL, SystemPrompt NVARCHAR(MAX) NOT NULL);
CREATE TABLE ChatSessions(
 Id BIGINT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE, ScenarioId INT NULL REFERENCES ChatScenarios(Id),
 Title NVARCHAR(200) NULL, CreatedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME());
CREATE TABLE ChatMessages(
 Id BIGINT IDENTITY PRIMARY KEY, SessionId BIGINT NOT NULL REFERENCES ChatSessions(Id) ON DELETE CASCADE,
 Role NVARCHAR(10) NOT NULL CHECK(Role IN('user','assistant')), Content NVARCHAR(MAX) NOT NULL, CorrectedContent NVARCHAR(MAX) NULL,
 CreatedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME());
CREATE TABLE LearnerErrors(  -- "Nhật ký lỗi": đúng 1 nguồn lỗi cho mỗi dòng
 Id BIGINT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE, SkillId TINYINT NOT NULL REFERENCES Skills(Id),
 PronunciationAttemptId BIGINT NULL REFERENCES PronunciationAttempts(Id), ChatMessageId BIGINT NULL REFERENCES ChatMessages(Id), StudyAnswerId BIGINT NULL REFERENCES StudyAnswers(Id),
 Detail NVARCHAR(500) NOT NULL, Correction NVARCHAR(500) NULL, IsResolved BIT NOT NULL DEFAULT 0, CreatedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME(),
 CONSTRAINT CK_OneSource CHECK((CASE WHEN PronunciationAttemptId IS NULL THEN 0 ELSE 1 END)+(CASE WHEN ChatMessageId IS NULL THEN 0 ELSE 1 END)+(CASE WHEN StudyAnswerId IS NULL THEN 0 ELSE 1 END)=1));

GO
/* ===== 6. LỘ TRÌNH CÁ NHÂN HÓA (CN 16) ===== */
CREATE TABLE UserSkillScores(
 Id BIGINT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE, SkillId TINYINT NOT NULL REFERENCES Skills(Id),
 Score DECIMAL(5,2) NOT NULL CHECK(Score BETWEEN 0 AND 100), MeasuredAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME());
CREATE TABLE LearningPlans(
 Id INT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE, StartDate DATE NOT NULL, EndDate DATE NOT NULL,
 Status NVARCHAR(10) NOT NULL DEFAULT 'active' CHECK(Status IN('active','done','cancelled')), CONSTRAINT CK_PlanDates CHECK(EndDate>=StartDate));
CREATE TABLE PlanTasks(
 Id INT IDENTITY PRIMARY KEY, PlanId INT NOT NULL REFERENCES LearningPlans(Id) ON DELETE CASCADE, SkillId TINYINT NOT NULL REFERENCES Skills(Id),
 Title NVARCHAR(200) NOT NULL, DueDate DATE NOT NULL, IsDone BIT NOT NULL DEFAULT 0,
 LessonId INT NULL REFERENCES GeneratedLessons(Id), PassageId INT NULL REFERENCES ReadingPassages(Id), ScenarioId INT NULL REFERENCES ChatScenarios(Id));
GO
